#!/usr/bin/env node
// Rewrites the index at the top of docs/internals/decisions.md: one row per
// [D-nn] entry, in number order, with its title and, when the entry says so,
// what replaced part of it. The entries are the source; the index is derived,
// so it cannot drift as long as this runs.
//
// It also makes the citations in the repository's Markdown links: each entry
// opens with its own anchor, a §n is written [§n], and every file that cites
// [D-nn] or [§n] ends in the link definitions for them.
//
//   node scripts/decisions-index.mjs          rewrite the index and the links
//   node scripts/decisions-index.mjs --check  exit 1 when either is stale or
//                                             the repo cites a missing entry (CI)
// A path argument works on another copy of the log, and leaves the links alone.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { outsideCode, prose, sections } from './lib/markdown.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const LOG = resolve(root, 'docs/internals/decisions.md');
const SPEC = resolve(root, 'docs/internals/design.md');
const FILE = resolve(process.argv.slice(2).find((a) => !a.startsWith('--')) ?? LOG);
const check = process.argv.includes('--check');
const START = '<!-- decisions-index:start (generated by scripts/decisions-index.mjs) -->';
const END = '<!-- decisions-index:end -->';
const LINKS = '<!-- citation links (generated by scripts/decisions-index.mjs) -->';

const text = readFileSync(FILE, 'utf8');
const begin = text.indexOf(START);
const end = text.indexOf(END);
if (begin < 0 || end < begin) {
	console.error(`decisions-index: markers not found in ${FILE}`);
	process.exit(2);
}

// An entry is a paragraph opening with **[D-nn] Title.** — the title is the
// bold run — after the anchor its citations link to. An entry trimmed to what
// still holds names what replaced the rest in one sentence, "… was replaced
// by [D-nn] …", anywhere in its text; every such sentence counts, since parts
// of one entry can be replaced by different ones.
const ENTRY = /^(?:<a id="D-\d+"><\/a>)?\*\*\[(D-(\d+))\]\s*(.*?)\*\*(.*)$/;
const rows = [];
let last = null;
const replacedBy = (line) =>
	[...line.matchAll(/\b(?:was|were) replaced by \[(D-\d+)\]/g)].map((r) => r[1]);
const lines = text.split('\n');
lines.forEach((line, i) => {
	const m = ENTRY.exec(line);
	if (!m) {
		last?.parts.push(...replacedBy(line));
		return;
	}
	const [, label, num, rawTitle, rest] = m;
	lines[i] = `<a id="${label}"></a>${line.replace(/^<a id="D-\d+"><\/a>/, '')}`;
	// The date in parentheses at the end of the title is noise in an index.
	const title = rawTitle.replace(/\s*\([^()]*(?:\([^()]*\)[^()]*)*\)\.?$/, '').replace(/\.$/, '');
	last = { num: Number(num), label, title, parts: replacedBy(rest) };
	rows.push(last);
});
for (const row of rows) {
	const parts = [...new Set(row.parts)].sort((a, b) => a.slice(2) - b.slice(2));
	row.status = parts.length ? `partly superseded by ${parts.map((p) => `[${p}]`).join(', ')}` : '';
}
rows.sort((a, b) => a.num - b.num);

const cell = (s) => s.replace(/\|/g, '\\|');
const table = [
	'| | Decision | Status |',
	'|---|---|---|',
	...rows.map((r) => `| [${r.label}] | ${cell(r.title)} | ${r.status} |`)
].join('\n');
const anchored = lines.join('\n');
const log = `${anchored.slice(0, anchored.indexOf(START))}${START}\n\n${table}\n\n${anchored.slice(anchored.indexOf(END))}`;

// Each Markdown file, as it should read: a bare §n bracketed, and the
// definitions for what it cites at its end.
const stale = [];
const unknown = [];
const relink = (file, body) => {
	const own = body.indexOf(`\n${LINKS}`);
	const cut = own < 0 ? body : body.slice(0, own).replace(/\n+$/, '\n');
	const bracketed = outsideCode(cut, (s) => s.replace(/(?<!\[)§(\d+(?:\.\d+)*)/g, '[§$1]'));
	const cited = new Set(
		[...prose(bracketed).matchAll(/\[(D-\d+|§\d+(?:\.\d+)*)\](?![(\]])/g)].map((m) => m[1])
	);
	if (!cited.size) return bracketed;
	const to = (target, anchor) =>
		`${target === file ? '' : relative(dirname(file), target)}#${anchor}`;
	const spec = sections(SPEC);
	const defs = [...cited]
		.sort((a, b) => a.localeCompare(b, 'en', { numeric: true }))
		.map((c) => {
			if (c.startsWith('D-')) return `[${c}]: ${to(LOG, c)}`;
			const anchor = spec.get(c.slice(1));
			if (!anchor) unknown.push(`${relative(root, file)}: ${c}`);
			return `[${c}]: ${to(SPEC, anchor)}`;
		});
	return `${bracketed}\n${LINKS}\n\n${defs.join('\n')}\n`;
};
const out = new Map();
if (FILE === LOG) {
	const md = execFileSync('git', ['ls-files', '*.md'], { cwd: root, encoding: 'utf8' })
		.split('\n')
		.filter((f) => f && !f.startsWith('docs/THIRD_PARTY'));
	for (const f of md) {
		const file = resolve(root, f);
		const before = file === LOG ? text : readFileSync(file, 'utf8');
		const after = relink(file, file === LOG ? log : before);
		if (after !== before) out.set(file, after);
	}
} else if (log !== text) out.set(FILE, log);

if (unknown.length) {
	console.error(
		`decisions-index: these cite a section design.md does not have:\n${unknown.join('\n')}`
	);
	process.exit(1);
}
if (check) {
	for (const file of out.keys()) stale.push(relative(root, file));
	if (stale.length) {
		console.error(
			`decisions-index: the index or the citation links are stale in ${stale.join(', ')}; run node scripts/decisions-index.mjs`
		);
		process.exit(1);
	}
	// A deleted entry's citations move to what replaced it; one left behind
	// points at nothing. CHANGELOG cites them too, and code that shows a
	// decision's number cites it without brackets.
	const have = new Set(rows.map((r) => r.label));
	const cited = execFileSync('git', ['grep', '--full-name', '-InowE', 'D-[0-9]+', ':/'], {
		cwd: root,
		encoding: 'utf8'
	});
	const missing = cited.split('\n').filter((l) => l && !have.has(/(D-\d+)$/.exec(l)[1]));
	if (missing.length) {
		console.error(
			`decisions-index: these cite an entry the log does not have:\n${missing.join('\n')}`
		);
		process.exit(1);
	}
} else {
	for (const [file, body] of out) writeFileSync(file, body);
}
